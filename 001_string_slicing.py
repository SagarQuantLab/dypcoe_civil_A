my_string = "This is civil students"

# access first element
print(my_string[0])

# access 'This'
print(my_string[0:4])

# access 'Ti'
print(my_string[0:4:2])

# last element
print(my_string[-1])

# reversed string
print(my_string[::-1])

# reverse students
print(my_string[:-9:-1])

# lower case 
print(my_string.lower())

# upper case
print(my_string.upper())

# replace string
replace_string = my_string.replace("s", "X")
print(replace_string)
